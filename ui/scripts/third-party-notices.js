#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from what ships: the non-dev dependency tree in package-lock.json
// (installed with the npm package) plus every package Vite bundles into dist/ (found with a real build).
// Usage: node scripts/third-party-notices.js [--no-build]
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const ui = path.resolve(import.meta.dirname, '..')
const lock = JSON.parse(fs.readFileSync(path.join(ui, 'package-lock.json'), 'utf8'))
const NOTICE_FILE = /^(licen[sc]e|copying|notice)([.\-_].*)?$/i

const pkgDirOf = (id) => { const i = id.lastIndexOf('/node_modules/'); if (i < 0) return null; const rest = id.slice(i + 14).split('/'); return id.slice(0, i + 14) + rest.slice(0, rest[0].startsWith('@') ? 2 : 1).join('/') }

async function bundledDirs() {
  const { build } = await import('vite')
  const dirs = new Set(), outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'notices-build-'))
  const collect = { name: 'collect-bundled-packages', generateBundle(_, bundle) { const css = [...this.getModuleIds(), ...this.getWatchFiles()].filter((id) => /\.css($|\?)/.test(id)); for (const id of [...css, ...Object.values(bundle).flatMap((chunk) => Object.keys(chunk.modules ?? {}))]) { const clean = id.replace(/^\0/, '').split('?')[0]; const dir = pkgDirOf(clean) ?? (clean.startsWith('vite/') ? path.join(ui, 'node_modules/vite') : null); if (dir) dirs.add(dir) } } }
  try { await build({ root: ui, configFile: path.join(ui, 'vite.config.js'), logLevel: 'warn', plugins: [collect], build: { outDir, emptyOutDir: true } }) }
  finally { fs.rmSync(outDir, { recursive: true, force: true }) }
  return dirs
}

const runtimeDirs = () => Object.entries(lock.packages).filter(([key, meta]) => key && !meta.dev && !meta.devOptional && !meta.link).map(([key]) => path.join(ui, key)).filter((dir) => fs.existsSync(path.join(dir, 'package.json')))

function describe(dir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const lockEntry = lock.packages[path.relative(ui, dir).split(path.sep).join('/')] ?? {}
  const license = manifest.license?.type ?? manifest.license ?? manifest.licenses?.map((l) => l.type ?? l).join(' OR ') ?? lockEntry.license ?? 'UNKNOWN'
  const files = fs.readdirSync(dir).filter((name) => NOTICE_FILE.test(name) && fs.statSync(path.join(dir, name)).isFile()).sort()
  return { name: manifest.name, version: manifest.version, license: String(license), homepage: typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url ?? manifest.homepage, texts: files.map((name) => ({ name, text: fs.readFileSync(path.join(dir, name), 'utf8').trim() })) }
}

const collect = (dirs) => { const out = new Map(); for (const dir of dirs) { const pkg = describe(dir); out.set(`${pkg.name}@${pkg.version}`, pkg) } return [...out.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)) }
const fence = (text) => { const ticks = '`'.repeat(Math.max(3, ...(text.match(/`+/g) ?? []).map((t) => t.length + 1))); return `${ticks}text\n${text}\n${ticks}` }
const section = (pkg) => [`### ${pkg.name}@${pkg.version}`, '', `License: ${pkg.license}${pkg.homepage ? `  \nSource: ${pkg.homepage.replace(/^git\+/, '')}` : ''}`, '', ...(pkg.texts.length ? pkg.texts.flatMap((t) => [`${t.name}:`, '', fence(t.text), '']) : [`No license file is included in the package; its manifest declares \`${pkg.license}\`.`, ''])].join('\n')

const runtime = collect(runtimeDirs())
const bundled = process.argv.includes('--no-build') ? [] : collect(await bundledDirs())
const runtimeKeys = new Set(runtime.map((p) => `${p.name}@${p.version}`))
const browserOnly = bundled.filter((p) => !runtimeKeys.has(`${p.name}@${p.version}`))

const doc = [
  '# Third-party notices', '',
  'OpenRod is licensed under Apache-2.0. It ships third-party software that keeps its own license. This file is generated by `node scripts/third-party-notices.js` from `package-lock.json` and a production build; do not edit it by hand. Inclusion does not imply endorsement. Third-party names and logos are trademarks of their owners; see `public/logos/SOURCES.md` for the logo sources and licenses.', '',
  '## NVIDIA OpenShell SDK', '',
  '`@nvidia/openshell-sdk` is redistributed unchanged from `vendor/nvidia-openshell-sdk-0.0.0.tgz` (built from NVIDIA OpenShell v0.1.2) under Apache-2.0. Upstream: https://github.com/NVIDIA/OpenShell. Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. The complete upstream license and notice are in `vendor/OPENSHELL-LICENSE`.', '',
  `## Bundled into the web interface (dist/)`, '',
  `${browserOnly.length} packages compiled into the browser bundle, including fonts. Packages that are also runtime dependencies are listed in the next section.`, '',
  ...browserOnly.map(section),
  `## Runtime dependencies (installed with the npm package)`, '',
  `${runtime.length} packages from the production dependency tree.`, '',
  ...runtime.map(section),
].join('\n')

fs.writeFileSync(path.join(ui, 'THIRD_PARTY_NOTICES.md'), doc.trimEnd() + '\n')
console.log(`THIRD_PARTY_NOTICES.md: ${browserOnly.length} bundled, ${runtime.length} runtime packages`)
for (const p of [...browserOnly, ...runtime].filter((p) => !p.texts.length)) console.log(`  no license file: ${p.name}@${p.version} (${p.license})`)
